import "server-only";
import { createCipheriv, createDecipheriv, createHash, hkdfSync, randomBytes } from "node:crypto";
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "../env";

/**
 * Object storage adapter (ADR-005, FR-DOC-008). The pilot stores blobs on local disk; an S3/MinIO
 * adapter implements the same interface. Every blob is encrypted at rest with AES-256-GCM under a
 * key derived from APP_ENCRYPTION_KEY, and is never publicly addressable: reads go through an
 * authorised route handler.
 */
export interface BlobStore {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Whether a blob is stored under the key (a cheap check, no decryption). */
  has(key: string): Promise<boolean>;
}

const MAGIC = Buffer.from("RB1");

function blobKey(): Buffer {
  return Buffer.from(
    hkdfSync("sha256", env().APP_ENCRYPTION_KEY, "rebp-blobs", "documents-v1", 32),
  );
}

export function sealBlob(data: Buffer): Buffer {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", blobKey(), iv);
  const ciphertext = Buffer.concat([cipher.update(data), cipher.final()]);
  return Buffer.concat([MAGIC, iv, cipher.getAuthTag(), ciphertext]);
}

export function openBlob(sealed: Buffer): Buffer {
  if (!sealed.subarray(0, 3).equals(MAGIC)) throw new Error("Unsupported blob format");
  const iv = sealed.subarray(3, 15);
  const tag = sealed.subarray(15, 31);
  const decipher = createDecipheriv("aes-256-gcm", blobKey(), iv);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(sealed.subarray(31)), decipher.final()]);
}

function root() {
  return path.resolve(env().STORAGE_DIR);
}

/** Keys are generated by the server (`yyyy/mm/<random>`); reject anything that could escape the root. */
function resolveKey(key: string): string {
  if (!/^[a-z0-9/_-]+$/i.test(key) || key.includes("..")) throw new Error("Invalid storage key");
  return path.join(root(), key);
}

const localStore: BlobStore = {
  async put(key, data) {
    const file = resolveKey(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, sealBlob(data), { mode: 0o600 });
  },
  async get(key) {
    return openBlob(await readFile(resolveKey(key)));
  },
  async has(key) {
    try {
      await access(resolveKey(key));
      return true;
    } catch {
      return false;
    }
  },
};

export const blobStore: BlobStore = localStore;

export function sha256Hex(data: Buffer): string {
  return createHash("sha256").update(data).digest("hex");
}

/** File signatures the portal accepts (FR-DOC-003): PDF, PNG, JPEG, WebP. */
function looksLike(mimeType: string, bytes: Buffer): boolean {
  const head = (n: number) => bytes.subarray(0, n);
  if (mimeType === "application/pdf") {
    if (head(5).toString("latin1") !== "%PDF-") return false;
    // A PDF that declares no pages (or only an empty page tree) renders as a viewer error;
    // treat it as unreadable so the officer gets the designed state instead (UX-035).
    const text = bytes.toString("latin1");
    const counts = [...text.matchAll(/\/Type\s*\/Pages\b[^>]*?\/Count\s+(\d+)/g)].map((m) =>
      Number(m[1]),
    );
    return counts.length === 0 || counts.some((n) => n > 0);
  }
  if (mimeType === "image/png") return head(4).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47]));
  if (mimeType === "image/jpeg") return head(3).equals(Buffer.from([0xff, 0xd8, 0xff]));
  if (mimeType === "image/webp")
    return (
      head(4).toString("latin1") === "RIFF" && bytes.subarray(8, 12).toString("latin1") === "WEBP"
    );
  return bytes.length > 0;
}

/**
 * Whether a stored file can actually be shown (UX-034/035): it exists, decrypts, and its bytes
 * are the type it claims — so a viewer shows a designed state instead of a broken frame.
 */
export async function blobReadable(key: string, mimeType: string): Promise<boolean> {
  try {
    return looksLike(mimeType, await blobStore.get(key));
  } catch {
    return false;
  }
}
