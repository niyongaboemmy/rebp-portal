#!/usr/bin/env node
/**
 * Writes src/components/icons/fluent.ts: the app's icons drawn from Microsoft's Fluent UI System
 * Icons (MIT) — the 20 px Regular glyph, and its Filled twin for active states. The paths are
 * copied as data, so the icons are plain SVG: no runtime package, no CSS-in-JS, no hooks, and
 * they render in Server Components. Run after changing scripts/fluent-icon-map.mjs:
 *
 *   pnpm --filter @rebp/web icons
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ICON_MAP } from "./fluent-icon-map.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const atoms = path.join(root, "node_modules/@fluentui/react-icons/lib/atoms/svg");
const out = path.join(root, "src/components/icons/fluent.ts");
const version = JSON.parse(
  fs.readFileSync(path.join(root, "node_modules/@fluentui/react-icons/package.json"), "utf8"),
).version;

const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

/** The `d` attributes of one icon variant (e.g. PersonAdd20Regular), and whether it mirrors in RTL. */
function variant(base, kind) {
  const name = `${base}20${kind}`;
  const files = [kebab(base), kebab(base).replace(/-?\d+$/, "")].map((f) =>
    path.join(atoms, `${f}.js`),
  );
  for (const file of files) {
    if (!fs.existsSync(file)) continue;
    const src = fs.readFileSync(file, "utf8");
    const at = src.indexOf(`export const ${name} =`);
    if (at < 0) continue;
    const start = src.indexOf("[", at);
    let depth = 0;
    let end = start;
    for (; end < src.length; end++) {
      if (src[end] === "[") depth++;
      else if (src[end] === "]" && --depth === 0) break;
    }
    const paths = JSON.parse(src.slice(start, end + 1));
    if (!Array.isArray(paths) || !paths.every((p) => typeof p === "string"))
      throw new Error(`${name}: not a mono-colour path list`);
    const tail = src.slice(end + 1, src.indexOf(";", end));
    return { paths, rtl: /flipInRtl:\s*true/.test(tail) };
  }
  throw new Error(`${name} not found in @fluentui/react-icons ${version}`);
}

const lines = [
  "// Generated by scripts/gen-fluent-icons.mjs from @fluentui/react-icons " + version + " (MIT,",
  "// Microsoft Fluent UI System Icons). Do not edit: change scripts/fluent-icon-map.mjs and rerun.",
  'import { fluentIcon } from "./fluent-icon";',
  "",
];
for (const [name, base] of Object.entries(ICON_MAP).sort(([a], [b]) => a.localeCompare(b))) {
  const regular = variant(base, "Regular");
  const filled = variant(base, "Filled");
  lines.push(
    `/** Fluent ${base} */`,
    `export const ${name} = fluentIcon(${JSON.stringify(name)}, ${JSON.stringify(regular.paths)}, ${JSON.stringify(filled.paths)}${regular.rtl ? ", true" : ""});`,
  );
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${lines.join("\n")}\n`);
console.log(
  `✓ ${Object.keys(ICON_MAP).length} Fluent icons → ${path.relative(root, out)} (@fluentui/react-icons ${version})`,
);
