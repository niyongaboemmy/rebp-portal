#!/usr/bin/env node
/**
 * Writes src/components/icons/nav.ts: the side-navigation icons drawn from Lucide (ISC), via the
 * @iconify-json/lucide data package (the rest of the app uses Fluent: gen-fluent-icons.mjs). Each icon's SVG body is copied as data and
 * sanitised to drawing elements and presentation attributes only, so the icons are plain SVG: no
 * runtime package, no CSS-in-JS, no hooks, and they render in Server Components. Run after
 * changing scripts/nav-icon-map.mjs:
 *
 *   pnpm --filter @rebp/web icons
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { NAV_ICON_MAP as ICON_MAP } from "./nav-icon-map.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const pkg = path.join(root, "node_modules/@iconify-json/lucide");
const out = path.join(root, "src/components/icons/nav.ts");
const { version } = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8"));
const data = JSON.parse(fs.readFileSync(path.join(pkg, "icons.json"), "utf8"));
const size = data.width ?? 24;

const TAGS = new Set(["path", "g", "circle", "ellipse", "rect", "line", "polyline", "polygon"]);
const ATTRS = new Set([
  "d",
  "cx",
  "cy",
  "r",
  "rx",
  "ry",
  "x",
  "y",
  "x1",
  "y1",
  "x2",
  "y2",
  "width",
  "height",
  "points",
  "fill",
  "stroke",
  "stroke-width",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-miterlimit",
  "fill-rule",
  "clip-rule",
  "opacity",
  "fill-opacity",
  "stroke-opacity",
  "transform",
]);

/** The icon's body with every element and attribute checked against the allow-lists. */
function body(name) {
  const icon = data.icons[name] ?? data.icons[data.aliases?.[name]?.parent];
  if (!icon) throw new Error(`${name} not found in @iconify-json/lucide ${version}`);
  if ((icon.width ?? size) !== size || (icon.height ?? size) !== size)
    throw new Error(`${name}: unexpected size`);
  return icon.body.replace(/<(\/?)(\w+)([^>]*?)(\/?)>/g, (_, close, tag, attrs, self) => {
    if (!TAGS.has(tag)) throw new Error(`${name}: unexpected <${tag}>`);
    if (close) return `</${tag}>`;
    const kept = [...attrs.matchAll(/([\w-]+)="([^"]*)"/g)]
      .filter(([, key, value]) => {
        if (!ATTRS.has(key)) throw new Error(`${name}: unexpected attribute ${key}`);
        return !/[<>]|url\(|javascript:/i.test(value);
      })
      .map(([, key, value]) => ` ${key}="${value}"`)
      .join("");
    return `<${tag}${kept}${self}>`;
  });
}

const lines = [
  `// Generated by scripts/gen-nav-icons.mjs from @iconify-json/lucide ${version} (ISC, Lucide).`,
  "// Do not edit: change scripts/nav-icon-map.mjs and rerun.",
  'import { svgIcon } from "./icon";',
  "",
];
for (const [name, base] of Object.entries(ICON_MAP).sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(
    `/** Lucide ${base} */`,
    `export const ${name} = svgIcon(${JSON.stringify(name)}, ${JSON.stringify(body(base))});`,
  );
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${lines.join("\n")}\n`);
console.log(
  `✓ ${Object.keys(ICON_MAP).length} Lucide nav icons → ${path.relative(root, out)} (@iconify-json/lucide ${version})`,
);
